// 02_first_file.js — your first JavaScript FILE.
// Run it from a terminal, inside this folder:   node 02_first_file.js
// (No Node installed? Lesson 02 shows how to run files from an HTML page —
//  that is how real websites do it. Online playgrounds work too: see references.html.)

// A file runs top to bottom, one statement at a time.
console.log("Hello from a file!");

// A variable is a named box that stores a value (lesson 04 covers them fully).
const apples = 3;
const eaten = 1;
console.log("Apples left:", apples - eaten); // the engine computes 3 - 1 first

// console.log accepts several values, separated by commas.
console.log("2 + 3 is", 2 + 3);

// Expected output:
//   Hello from a file!
//   Apples left: 2
//   2 + 3 is 5
