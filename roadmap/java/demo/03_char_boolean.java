/* Java lab demo 03 — char and boolean, including a non-ASCII character.
 *
 * Run:  javac 03_char_boolean.java  &&  java CharType
 */
class CharType {
  public static void main(String[] args) {
    char  o = 'ω';
    boolean  b = true;
    System.out.format("o = %c%n", o);
    System.out.format("b = %b%n", b);
  }
}
